package com.farmgame.sandbox.api;

import com.farmgame.core.crop.Crop;

/**
 * Команды, которые игрок может отдавать роботу.
 *
 * <p>Каждый метод <b>блокирующий</b>: он возвращает управление, когда робот
 * действительно выполнил действие в игровом мире (доехал, полил и т.д.).
 * Благодаря этому код игрока читается как обычная последовательная программа.
 *
 * <p>При нарушении правил (выезд за поле, посадка на занятую грядку)
 * бросается {@link RobotActionException}.
 */
public interface RobotApi {

    /** Переместиться в клетку {@code (x, y)}. */
    void moveTo(int x, int y);

    /** Текущая координата X робота. */
    int getX();

    /** Текущая координата Y робота. */
    int getY();

    /** Посадить культуру на грядку под роботом. */
    void plant(Crop crop);

    /** Полить грядку под роботом (без полива культура не растёт). */
    void water();

    /**
     * Собрать урожай под роботом.
     *
     * @return сколько единиц собрано; 0, если культура ещё не созрела
     */
    int harvest();

    /**
     * Подождать, ничего не делая. Пока робот ждёт, культуры продолжают расти.
     *
     * @param seconds игровые секунды (неотрицательное число)
     */
    void pause(double seconds);

    /** Написать сообщение в игровую консоль. */
    void say(String message);
}
